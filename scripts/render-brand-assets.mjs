#!/usr/bin/env node
// Draws the source artwork in assets/ from the mark in src/lib/logoMark.ts,
// then `npm run assets` turns it into every native icon and splash size.
//
//   npm run assets:render     # rewrite assets/*.png and assets/logo.svg
//   npm run assets            # render, then generate the iOS and Android sizes
//
// Rendered by Chromium through Playwright (already a dev dependency) so the
// PNGs come from the same SVG the app draws. When a designed logo replaces
// the R, drop the new files into assets/ and run only
// `npx capacitor-assets generate --ios --android`; this script is for the
// placeholder-free R mark we launch with.
//
// `capacitor-assets generate` also reformats android/app/src/main/
// AndroidManifest.xml (whitespace only) every time it runs. Revert that
// file rather than committing the churn: git checkout -- <that path>.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { MARK_FROM, MARK_INK, MARK_R_PATH, MARK_TO, markGlyphTransform } from '../src/lib/logoMark.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = `${root}assets/`;

// Tokens from src/theme/tokens.css: the page background at the end of the
// light and dark gradients, which is what surrounds the splash.
const LIGHT_BG = '#FAF9F5';
const DARK_BG = '#18140F';

const gradient = `<linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="${MARK_FROM}"/><stop offset="1" stop-color="${MARK_TO}"/>
  </linearGradient>`;
const r = (share) => `<path d="${MARK_R_PATH}" transform="${markGlyphTransform(share)}" fill="${MARK_INK}"/>`;

const svg = (body, defs = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><defs>${defs}</defs>${body}</svg>`;

// Home-screen icon: square and full bleed (iOS rounds it, and a pre-rounded
// icon gets rounded twice). The R is larger than in the app so it still
// reads at 40px.
const ICON_SHARE = 0.46;
const icon = svg(`<rect width="100" height="100" fill="url(#g)"/>${r(ICON_SHARE)}`, gradient);

// Android adaptive icon: the launcher masks a 108dp layer to a circle or
// squircle and may show as little as the middle ~61%. The R's box
// (0.36 × 0.40 of the layer) keeps its corners inside that circle.
const foreground = svg(r(0.40));
const background = svg(`<rect width="100" height="100" fill="url(#g)"/>`, gradient);

// Splash: the in-app mark, small and centred, on the page colour. Every
// device crops this square differently, so nothing goes near the edges.
const splash = (bg) =>
  svg(
    `<rect width="100" height="100" fill="${bg}"/>
     <g transform="translate(40 40) scale(0.2)">
       <rect width="100" height="100" rx="30" fill="url(#g)"/>${r(0.33)}
     </g>`,
    gradient,
  );

// For use anywhere outside the app (the site, the store listing, a
// designer): the mark as the app shows it, with its corners.
const logoSvg = svg(`<rect width="100" height="100" rx="30" fill="url(#g)"/>${r(0.33)}`, gradient);

const renders = [
  ['icon-only.png', icon, 1024, false],
  ['icon-foreground.png', foreground, 1024, true],
  ['icon-background.png', background, 1024, false],
  ['splash.png', splash(LIGHT_BG), 2732, false],
  ['splash-dark.png', splash(DARK_BG), 2732, false],
];

mkdirSync(out, { recursive: true });
writeFileSync(`${out}logo.svg`, `${logoSvg}\n`);

// Android 12+ ignores splash.png: the system draws its own splash from
// windowSplashScreenAnimatedIcon (styles.xml) on the page colour. As a
// vector it stays sharp at the size the system chooses. 288dp canvas, of
// which the system shows the middle 192dp circle; the 128dp mark's corners
// stay inside it.
const [gx, gy, gs] = (() => {
  const m = /translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)/.exec(markGlyphTransform(0.33));
  return [m[1], m[2], m[3]];
})();
const splashIcon = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/render-brand-assets.mjs from src/lib/logoMark.ts. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="288dp" android:height="288dp"
    android:viewportWidth="288" android:viewportHeight="288">
    <group android:translateX="80" android:translateY="80" android:scaleX="1.28" android:scaleY="1.28">
        <path android:pathData="M30,0 H70 A30,30 0 0 1 100,30 V70 A30,30 0 0 1 70,100 H30 A30,30 0 0 1 0,70 V30 A30,30 0 0 1 30,0 Z">
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="100" android:endY="100">
                    <item android:offset="0" android:color="${MARK_FROM}"/>
                    <item android:offset="1" android:color="${MARK_TO}"/>
                </gradient>
            </aapt:attr>
        </path>
        <group android:translateX="${gx}" android:translateY="${gy}" android:scaleX="${gs}" android:scaleY="-${gs}">
            <path android:fillColor="${MARK_INK}" android:pathData="${MARK_R_PATH}"/>
        </group>
    </group>
</vector>
`;
writeFileSync(`${root}android/app/src/main/res/drawable/splash_icon.xml`, splashIcon);
console.log('android/app/src/main/res/drawable/splash_icon.xml');

const browser = await chromium.launch();
try {
  for (const [name, source, size, transparent] of renders) {
    const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
    await page.setContent(
      `<!doctype html><html><body style="margin:0;background:transparent">
       <div style="width:${size}px;height:${size}px">${source.replace('<svg ', `<svg width="${size}" height="${size}" `)}</div>
       </body></html>`,
    );
    await page.screenshot({ path: `${out}${name}`, omitBackground: transparent, clip: { x: 0, y: 0, width: size, height: size } });
    await page.close();
    console.log(`assets/${name}  ${size}×${size}${transparent ? '  transparent' : ''}`);
  }
} finally {
  await browser.close();
}
console.log('assets/logo.svg');
